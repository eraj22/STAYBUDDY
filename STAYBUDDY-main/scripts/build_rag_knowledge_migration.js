// Generate the versioned chatbot seed from the reviewed application reference.
// Run with --write after reviewing a change to docs/rag/STAYBUDDY_KNOWLEDGE.md.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const source = path.join(root, 'docs', 'rag', 'STAYBUDDY_KNOWLEDGE.md');
const destination = path.join(root, 'migrations', '040_rag_application_knowledge.sql');
const STAFF_ONLY = new Set(['KB026', 'KB027', 'KB028', 'KB036']);

function articlesFromMarkdown(markdown) {
  const sections = [...markdown.matchAll(/^## (KB\d{3}) (.+)\r?\n([\s\S]*?)(?=^## |$(?![\s\S]))/gm)];
  const articles = sections.map(([, id, title, body]) => {
    const metadata = body.match(/^Audience: (.+?)\. Category: ([a-z_]+)\. Status: (.+?)\.$/m);
    if (!metadata) throw new Error(`Missing audience, category or status for ${id}`);
    const paragraphs = body.trim().split(/\r?\n\s*\r?\n/)
      .filter(p => !/^(Audience:|Sources:)/.test(p))
      .map(p => p.replace(/\r?\n/g, ' ').trim())
      .filter(Boolean);
    if (!paragraphs.length || paragraphs.some(p => p.length < 20 || p.length > 8000)) {
      throw new Error(`Invalid retrieval paragraph in ${id}`);
    }
    return { id, title: title.trim(), category: metadata[2], audience: metadata[1], paragraphs };
  });
  if (articles.length !== 36 || new Set(articles.map(a => a.id)).size !== 36) {
    throw new Error(`Expected 36 distinct knowledge articles, found ${articles.length}`);
  }
  return articles.filter(a => !STAFF_ONLY.has(a.id));
}

const sqlLiteral = value => `'${value.replaceAll("'", "''")}'`;

function migrationSql(articles) {
  const documents = articles.map(a => `  (${sqlLiteral(`manual-${a.id.toLowerCase()}`)},${sqlLiteral(`${a.id} ${a.title}`)},${sqlLiteral(a.category)},ARRAY['all']::text[],'help_article',${sqlLiteral(`docs/rag/STAYBUDDY_KNOWLEDGE.md#${a.id}`)})`).join(',\n');
  const chunks = articles.flatMap(a => a.paragraphs.map((paragraph, index) =>
    `  (${sqlLiteral(`manual-${a.id.toLowerCase()}`)},${index},${sqlLiteral(paragraph)})`)).join(',\n');
  return `-- Generated by scripts/build_rag_knowledge_migration.js from docs/rag/STAYBUDDY_KNOWLEDGE.md.\n` +
    `-- Public explanatory articles only. Staff-only KB026-028 and KB036 are excluded.\n` +
    `-- DO NOTHING preserves administrator corrections on repeat application.\n` +
    `BEGIN;\n` +
    `INSERT INTO chatbot_knowledge_documents (slug,title,category,audience,source_kind,source_reference)\nVALUES\n${documents}\nON CONFLICT (slug) DO NOTHING;\n` +
    `INSERT INTO chatbot_knowledge_chunks (document_id,chunk_index,content)\n` +
    `SELECT d.id,v.chunk_index,v.content FROM chatbot_knowledge_documents d\n` +
    `JOIN (VALUES\n${chunks}\n) AS v(slug,chunk_index,content) ON d.slug=v.slug\n` +
    `ON CONFLICT (document_id,chunk_index) DO NOTHING;\nCOMMIT;\n`;
}

if (require.main === module) {
  const expected = migrationSql(articlesFromMarkdown(fs.readFileSync(source, 'utf8')));
  if (process.argv.includes('--write')) {
    fs.writeFileSync(destination, expected, 'utf8');
    console.log(`Wrote ${destination}`);
  } else if (fs.existsSync(destination) && fs.readFileSync(destination, 'utf8') === expected) {
    console.log('RAG knowledge migration matches the reference');
  } else {
    console.error('RAG knowledge migration is missing or differs from the reference; run --write after review.');
    process.exitCode = 1;
  }
}

module.exports = { articlesFromMarkdown, migrationSql, STAFF_ONLY };
